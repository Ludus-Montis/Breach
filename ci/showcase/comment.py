#!/usr/bin/env python3
"""The PR's one showcase comment (spec 44 step 3), found by its marker and edited in place:
a row per scenario with its stills, the clip's link, its tick median and any behaviour it is
named for and didn't show ("breaking off: not seen"), then a link to the Showcase tab. A
failed capture leaves a comment saying so, with the run's link; the PR's checks don't change.

Usage:
  comment.py body <capture.json> <site-url>   - the comment for a capture
  comment.py failed <run-url> <sha>           - the comment for a failed capture
"""
import json
import sys

MARKER = "<!-- showcase-capture -->"
FOOTER = "---\n_Generated by [Claude Code](https://claude.ai/code)_\n"
MOMENTS = ("first", "contact", "midpoint", "last")


def _row(made: dict) -> str:
    stills = " ".join(
        f"![{m}]({made['stills'][m]})" for m in MOMENTS if m in made["stills"]
    )
    median = made.get("timings", {}).get("tick_median_ms")
    tick = f"{median:.2f} ms" if median is not None else "n/a"
    missing = made.get("missing") or []
    seen = ", ".join(f"{b.replace('_', ' ')}: not seen" for b in missing) or "all seen"
    return (f"| `{made['name']}` | {stills} | [clip]({made['clip']}) | {tick} | "
            f"{made['ticks']} | {seen} |")


def body(capture: dict, site_url: str) -> str:
    lines = [
        MARKER,
        f"## Showcase: {capture['commit'][:7]}",
        "",
        "| Scenario | Stills (first, contact, midpoint, last) | Clip | Tick (median) | Ticks "
        "| Behaviours |",
        "|---|---|---|---|---|---|",
        *(_row(made) for made in capture["scenarios"]),
        "",
        f"[The run]({capture['run']}) · [all captures on the Showcase tab]({site_url})",
        "",
        FOOTER,
    ]
    return "\n".join(lines)


def failed(run_url: str, sha: str) -> str:
    return "\n".join([
        MARKER,
        f"## Showcase: {sha[:7]}",
        "",
        f"The capture failed; see [the run]({run_url}). Advisory only: the PR's checks are "
        "unchanged.",
        "",
        FOOTER,
    ])


def main(arguments: list) -> int:
    if len(arguments) == 3 and arguments[0] == "body":
        print(body(json.load(open(arguments[1], encoding="utf-8")), arguments[2]))
    elif len(arguments) == 3 and arguments[0] == "failed":
        print(failed(arguments[1], arguments[2]))
    else:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
