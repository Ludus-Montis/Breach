"""Tests for comment (spec 44 step 3): the PR's one showcase comment, found by its marker,
with a row per scenario; and the one a failed capture leaves."""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import comment  # noqa: E402

SITE = "https://ludus-montis.github.io/Breach/#showcase"
RUN = "https://github.com/o/r/actions/runs/1"
FOOTER = "---\n_Generated by [Claude Code](https://claude.ai/code)_"


def scenario(name: str, missing: list) -> dict:
    return {
        "name": name,
        "clip": f"https://x/{name}.webm",
        "stills": {"first": f"https://x/{name}-first.webp", "last": f"https://x/{name}-last.webp"},
        "ticks": 291,
        "missing": missing,
        "timings": {"rounds": 5, "tick_median_ms": 0.0512, "tick_p95_ms": 0.09},
    }


CAPTURE = {
    "commit": "5eb56236f64a77e64420a11f60b9aac22ef012b4",
    "run": RUN,
    "scenarios": [scenario("field_break_off", ["breaking_off"]),
                  scenario("field_waves_rout", [])],
}


class CommentTest(unittest.TestCase):
    def test_it_starts_with_the_marker_and_ends_with_the_footer(self):
        body = comment.body(CAPTURE, SITE)
        self.assertTrue(body.startswith(comment.MARKER))
        self.assertTrue(body.rstrip().endswith(FOOTER))

    def test_a_row_per_scenario_with_its_stills_clip_and_tick_median(self):
        body = comment.body(CAPTURE, SITE)
        row = next(line for line in body.splitlines() if "field_waves_rout" in line)
        self.assertIn("![first](https://x/field_waves_rout-first.webp)", row)
        self.assertIn("![last](https://x/field_waves_rout-last.webp)", row)
        self.assertIn("[clip](https://x/field_waves_rout.webm)", row)
        self.assertIn("0.05 ms", row)
        self.assertIn("all seen", row)
        self.assertIn(SITE, body)
        self.assertIn("5eb5623", body)

    def test_a_behaviour_not_seen_is_said(self):
        row = next(line for line in comment.body(CAPTURE, SITE).splitlines()
                   if "field_break_off" in line)
        self.assertIn("breaking off: not seen", row)

    def test_a_failed_capture_says_so_and_links_the_run(self):
        body = comment.failed(RUN, "5eb56236f64a")
        self.assertTrue(body.startswith(comment.MARKER))
        self.assertIn("failed", body)
        self.assertIn(RUN, body)
        self.assertIn("5eb5623", body)
        self.assertTrue(body.rstrip().endswith(FOOTER))


if __name__ == "__main__":
    unittest.main()
