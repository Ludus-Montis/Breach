"""Generate DECISIONS_INDEX.md from the design spec's Decision ledger.

The ledger is most of the spec, too long for an agent to read whole. The index gives one
line per Decision with where it starts and what superseded or amended it, so an agent
reads the index and then only the Decisions it needs (AI_First_Development_Kit
principles/agent-sessions.md, rule 4).

    python3 tools/decisions_index.py          # rewrite DECISIONS_INDEX.md
    python3 tools/decisions_index.py --check  # exit 1 if it is out of date
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "Breach — Reverse Tower Defense Design Spec.md"
INDEX = ROOT / "DECISIONS_INDEX.md"

HEADING = re.compile(r"^### Decision (\d+) — (.+?)\s*$")
SUPERSEDED_NOTE = re.compile(r"^> Superseded by Decision (\d+)")
LINK_FIELD = re.compile(r"^\*\*(Supersedes|Amends):\*\*\s*(.+)$")
DECISION_REF = re.compile(r"Decision (\d+)")


def parse(lines):
    """Return {number: {title, line, superseded_by, amended_by}}."""
    decisions = {}
    current = None
    for line_no, line in enumerate(lines, start=1):
        heading = HEADING.match(line)
        if heading:
            current = int(heading.group(1))
            decisions[current] = {
                "title": heading.group(2),
                "line": line_no,
                "superseded_by": set(),
                "amended_by": set(),
            }
            continue
        if current is None:
            continue
        note = SUPERSEDED_NOTE.match(line)
        if note:
            decisions[current]["superseded_by"].add(int(note.group(1)))
        field = LINK_FIELD.match(line)
        if field:
            key = "superseded_by" if field.group(1) == "Supersedes" else "amended_by"
            for ref in DECISION_REF.findall(field.group(2)):
                decisions.setdefault(int(ref), {}).setdefault(key, set()).add(current)
    return {n: d for n, d in decisions.items() if "title" in d}


def status(decision):
    parts = []
    if decision["superseded_by"]:
        parts.append("superseded by " + ", ".join(map(str, sorted(decision["superseded_by"]))))
    if decision["amended_by"]:
        parts.append("amended by " + ", ".join(map(str, sorted(decision["amended_by"]))))
    return "; ".join(parts)


def render(decisions):
    out = [
        "# Decisions index",
        "",
        "Generated by `python3 tools/decisions_index.py` from the `## Decisions` section of",
        "`Breach — Reverse Tower Defense Design Spec.md`. Don't edit by hand: the pre-commit",
        "check fails when it is out of date. Read a Decision by its line, e.g.",
        "`sed -n '<line>,/^### Decision/p'` on the spec, rather than reading the whole spec.",
        "",
        "| # | Decision | Line | Status |",
        "|---|---|---|---|",
    ]
    for number in sorted(decisions):
        d = decisions[number]
        title = d["title"].replace("|", "\\|")
        out.append(f"| {number} | {title} | {d['line']} | {status(d)} |")
    return "\n".join(out) + "\n"


def main():
    lines = SPEC.read_text(encoding="utf-8").splitlines()
    text = render(parse(lines))
    if "--check" in sys.argv:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("DECISIONS_INDEX.md is out of date: run python3 tools/decisions_index.py")
            return 1
        return 0
    INDEX.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
